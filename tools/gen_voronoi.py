print("{")
print("    const char* label;    // nullptr for unlabeled filler cells")
print("    uint32_t fillColor;   // 0xRRGGBB")
print("    std::vector<std::pair<float,float>> polygon; // absolute px, voronoi-field-local (add headerOffsetY when drawing)")
print("};")
print()
print(f"static constexpr float kVoronoiFieldWidth = {float(W)}f;")
print(f"static constexpr float kVoronoiFieldHeight = {float(H)}f;")
print(f"static constexpr float kVoronoiHeaderHeight = {float(HEADER_H)}f;")
print()
print("inline const std::vector<VoronoiCellGeo>& voronoiCells()")
print("{")
print("    static const std::vector<VoronoiCellGeo> cells = {")

for i, (name, sx, sy, tag) in enumerate(seeds):
    poly = polygon_for(i)
    pts_str = ", ".join(f"{{{x:.2f}f, {y:.2f}f}}" for x, y in poly)
    label = "nullptr" if tag is None else f'"{tag}"'
    print(f'        {{ {label}, {colors[name]}, {{ {pts_str} }} }}, // {name}')

print("    };")
print("    return cells;")
print("}")
print()
print("} // namespace ui")
print("} // namespace phellipe")
